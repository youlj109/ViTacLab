def _apply_left_touch_joint_offset(frame: dict[str, Any], arm_j: np.ndarray, x_offset: float, gain: float) -> np.ndarray:
    name = str(frame.get("name", ""))
    out = np.asarray(arm_j, dtype=np.float64).copy()
    if "Left_Touch01" not in name or out.size < 1:
        return out
    out[0] += float(gain) * float(x_offset)
    return out



def _save_npz(out_dir: str, name: str, bufs: dict[str, list[np.ndarray]]):
    if not bufs:
        return None, 0
    first = next(iter(bufs.keys()))
    if not bufs[first]:
        return None, 0
    path = os.path.join(out_dir, name)
    t_len = len(bufs[first])
    np.savez_compressed(path, **{k: np.stack(v, 0) for k, v in bufs.items() if v})
    return path, t_len


def _warmup_tactile_nominal(env) -> list[str]:
    warmed: list[str] = []
    scene = env.scene
    for name in DUAL_TACTILE_SENSOR_NAMES:
        if name not in scene.sensors:
            continue
        sensor = scene[name]
        for _ in range(3):
            try:
                sensor.get_initial_render()
                warmed.append(name)
                break
            except RuntimeError:
                continue
            except Exception:
                break
    return warmed


def _reset_and_warmup(env: Any, act_dim: int, settle_steps: int) -> list[str]:
    env.reset()
    zero_actions = {
        "right_hand": torch.zeros(env.num_envs, act_dim, device=env.device),
        "left_hand": torch.zeros(env.num_envs, act_dim, device=env.device),
    }
    for _ in range(max(0, int(settle_steps))):
        env.step(zero_actions)
    return _warmup_tactile_nominal(env)


def _read_tactile_from_scene(
    env,
    env_idx: int,
    *,
    camera_brightness_factor: float,
    camera_noise_std: float,
    camera_blur_kernel: int,
) -> dict[str, np.ndarray]:
    out: dict[str, np.ndarray] = {}
    scene = env.scene
    num_tactile = len(DUAL_TACTILE_SENSOR_NAMES)
    tactile_pose_list: list[torch.Tensor] = []
    norm_list, shear_list, rgb_list = [], [], []
    for name in DUAL_TACTILE_SENSOR_NAMES:
        if name not in scene.sensors:
            continue
        try:
            data = scene[name].data
        except RuntimeError:
            try:
                scene[name].get_initial_render()
                data = scene[name].data
            except Exception:
                continue
        pos_w = getattr(data, "pos_w", getattr(scene[name], "pos_w", None))
        quat_w = getattr(data, "quat_w_ros", None)
        if quat_w is None:
            quat_w = getattr(data, "quat_w", getattr(scene[name], "quat_w", None))
        if pos_w is not None and quat_w is not None:
            tactile_pose_list.append(
                torch.cat((pos_w - scene.env_origins, quat_w), dim=-1)[env_idx].detach().cpu()
            )
        nf = getattr(data, "tactile_normal_force", None)
        sf = getattr(data, "tactile_shear_force", None)
        rgb = getattr(data, "tactile_rgb_image", None)
        if nf is not None:
            nf_e = nf[env_idx].detach().cpu()
            nf_e = torch.nan_to_num(nf_e, nan=0.0, posinf=0.0, neginf=0.0)
            norm_list.append(nf_e)
        if sf is not None:
            sf_e = sf[env_idx].detach().cpu()
            sf_e = torch.nan_to_num(sf_e, nan=0.0, posinf=0.0, neginf=0.0)
            shear_list.append(sf_e)
        if rgb is not None:
            rgb_e = _img_to_uint8_torch(rgb[env_idx]).detach().cpu()
            rgb_list.append(rgb_e)
    if len(tactile_pose_list) != num_tactile:
        # Some TacSL builds expose force/RGB but no standard sensor pose.  Use
        # the ten physical fingertip rigid-body poses, preserving the canonical
        # left-five then right-five order used by DUAL_TACTILE_SENSOR_NAMES.
        tactile_pose_list = []
        for robot in (env.left_hand, env.right_hand):
            body_names = [str(name).lower() for name in robot.body_names]
            for finger in ("ff", "lf", "mf", "rf", "th"):
                search_terms = (f"{finger}distal", f"{finger}_tip", finger)
                body_idx = next(
                    (
                        index
                        for term in search_terms
                        for index, body_name in enumerate(body_names)
                        if term in body_name
                    ),
                    None,
                )
                if body_idx is None:
                    tactile_pose_list = []
                    break
                tactile_pose_list.append(
                    torch.cat(
                        (
                            robot.data.body_pos_w[:, body_idx] - scene.env_origins,
                            robot.data.body_quat_w[:, body_idx],
                        ),
                        dim=-1,
                    )[env_idx]
                    .detach()
                    .cpu()
                )
            if not tactile_pose_list:
                break
    if len(tactile_pose_list) == num_tactile:
        out["tactile_pos"] = torch.stack(tactile_pose_list, dim=0).numpy()
    tactile_hw = None
    try:
        tactile_hw = env.cfg.scene._tactile_params()["tactile_array_size"]
    except Exception:
        pass
    if len(norm_list) == num_tactile and tactile_hw is not None:
        stacked = torch.stack(norm_list, dim=0)
        out["tactile_normal_force"] = stacked.reshape(num_tactile, tactile_hw[0], tactile_hw[1], 1).numpy()
    if len(shear_list) == num_tactile and tactile_hw is not None:
        stacked = torch.stack(shear_list, dim=0)
        out["tactile_shear_force"] = stacked.reshape(num_tactile, tactile_hw[0], tactile_hw[1], 2).numpy()
    if len(rgb_list) == num_tactile:
        out["tactile_rgb_image"] = torch.stack(rgb_list, dim=0).numpy()
    for cam_name in ("third_person_camera", "twist_camera"):
        if cam_name not in scene.sensors:
            continue
        cam = scene[cam_name]
        cam_rgb = cam.data.output.get("rgb", None)
        if cam_rgb is not None:
            cam_np = _img_to_uint8_torch(cam_rgb[env_idx]).detach().cpu().numpy()
            out[cam_name] = _postprocess_rgb_image(
                cam_np,
                brightness_factor=camera_brightness_factor,
                noise_std=camera_noise_std,
                blur_kernel=camera_blur_kernel,
            )
        cam_pos_w = getattr(cam.data, "pos_w", None)
        cam_quat_w = getattr(cam.data, "quat_w_ros", None)
        if cam_quat_w is None:
            cam_quat_w = getattr(cam.data, "quat_w", None)
        if cam_pos_w is not None and cam_quat_w is not None:
            cam_pose = torch.cat(
                (cam_pos_w - scene.env_origins, cam_quat_w), dim=-1
            )[env_idx]
            out[f"{cam_name}_pos"] = cam_pose.detach().cpu().numpy()[None, :]
    return out


