def _load_dual_keyframes(path: Path) -> dict[str, dict[str, Any]]:
    data = json.loads(path.read_text(encoding="utf-8"))
    keyframes = data.get("keyframes", {})
    if not isinstance(keyframes, dict):
        raise RuntimeError(f"Missing keyframes dict in {path}")
    return {str(name): dict(frame) for name, frame in keyframes.items() if isinstance(frame, dict)}


def _load_dual_init_keyframe(path: Path) -> dict[str, Any]:
    keyframes = _load_dual_keyframes(path)
    init = keyframes.get("Init")
    if not isinstance(init, dict):
        raise RuntimeError(f"Missing 'Init' keyframe in {path}")
    return init


def _frame_side(frame: dict[str, Any], side: str) -> dict[str, Any]:
    prefix = f"{side}_"
    return {
        "marker_pos_w": frame[f"marker_{prefix}pos_w"],
        "marker_quat_wxyz": frame.get(f"marker_{prefix}quat_wxyz", []),
        "marker_euler_xyz": frame.get(f"marker_{prefix}euler_xyz", []),
        "arm_joint_pos": frame.get(f"arm_{prefix}joint_pos", []),
        "hand_joint_pos_shadow_order": frame.get(f"hand_{prefix}joint_pos_shadow_order", []),
    }


def _compose_dual_frame(name: str, right_frame: dict[str, Any], left_frame: dict[str, Any]) -> dict[str, Any]:
    right = _frame_side(right_frame, "right")
    left = _frame_side(left_frame, "left")
    return {
        "name": name,
        "marker_right_pos_w": right["marker_pos_w"],
        "marker_right_quat_wxyz": right["marker_quat_wxyz"],
        "marker_right_euler_xyz": right["marker_euler_xyz"],
        "marker_left_pos_w": left["marker_pos_w"],
        "marker_left_quat_wxyz": left["marker_quat_wxyz"],
        "marker_left_euler_xyz": left["marker_euler_xyz"],
        "arm_right_joint_pos": right["arm_joint_pos"],
        "arm_left_joint_pos": left["arm_joint_pos"],
        "hand_right_joint_pos_shadow_order": right["hand_joint_pos_shadow_order"],
        "hand_left_joint_pos_shadow_order": left["hand_joint_pos_shadow_order"],
    }


def _build_dual_phase_frames(keyframes: dict[str, dict[str, Any]], phase: int) -> list[dict[str, Any]]:
    right_branch = tuple(name for name in _RIGHT_BRANCH_KEYFRAMES[phase] if name in keyframes)
    missing = [name for name in (*_SHARED_DUAL_KEYFRAMES, *_LEFT_BRANCH_KEYFRAMES) if name not in keyframes]
    if not right_branch:
        missing.append("one of right branch keyframes")
    if missing:
        raise RuntimeError(f"Missing dual keyframes: {missing}")
    frames: list[dict[str, Any]] = []
    for name in _SHARED_DUAL_KEYFRAMES:
        frames.append(_compose_dual_frame(name, keyframes[name], keyframes[name]))

    left_hold = keyframes[_LEFT_BRANCH_KEYFRAMES[-1]]
    max_len = max(len(_LEFT_BRANCH_KEYFRAMES), len(right_branch))
    for i in range(max_len):
        left_name = _LEFT_BRANCH_KEYFRAMES[i] if i < len(_LEFT_BRANCH_KEYFRAMES) else _LEFT_BRANCH_KEYFRAMES[-1]
        right_name = right_branch[i] if i < len(right_branch) else right_branch[-1]
        left_frame = keyframes[left_name] if i < len(_LEFT_BRANCH_KEYFRAMES) else left_hold
        right_frame = keyframes[right_name]
        frames.append(_compose_dual_frame(f"{left_name}__{right_name}", right_frame, left_frame))
    return frames


def _apply_x_offset(frame: dict[str, Any], x_offset: float) -> dict[str, Any]:
    if abs(float(x_offset)) <= 1e-9:
        return frame
    out = dict(frame)
    name = str(out.get("name", ""))
    for key in ("marker_left_pos_w", "marker_right_pos_w"):
        if key not in out:
            continue
        should_shift = False
        if "Left_Touch01" in name and key == "marker_left_pos_w":
            should_shift = True
        if ("Right_Finish01_02" in name or "Right_Finish01_03" in name) and key == "marker_right_pos_w":
            should_shift = True
        if should_shift:
            pos = np.asarray(out[key], dtype=np.float64).copy()
            if pos.size >= 1:
                pos[0] += float(x_offset)
                out[key] = pos.tolist()
    return out


def _add_hand_noise(hand: np.ndarray, noise: float) -> np.ndarray:
    h = np.asarray(hand, dtype=np.float64).ravel()[:24]
    if h.size != 24:
        return h
    amp = max(0.0, float(noise))
    if amp <= 0.0:
        return h
    return h + np.random.uniform(-amp, amp, size=h.shape)


def _side_needs_x_offset_ik(frame: dict[str, Any], side: str, x_offset: float) -> bool:
    if abs(float(x_offset)) <= 1e-9:
        return False
    name = str(frame.get("name", ""))
    if side == "left" and "Left_Touch01" in name:
        return True
    if side == "right" and ("Right_Finish01_02" in name or "Right_Finish01_03" in name):
        return True
    return False


