def _compute_teleop_target(
    control,
    marker_pos: np.ndarray,
    marker_euler: np.ndarray,
    hand_j: np.ndarray,
    *,
    initial_arm_joints: np.ndarray,
    reference_arm_joints: np.ndarray,
    reference_weights: np.ndarray,
):
    """Call VideoTeleopControl.compute with backward compatibility.

    Some remote environments have an older signature that only accepts
    (marker_pos, marker_euler, hand_joints).
    """
    try:
        params = inspect.signature(control.compute).parameters
    except Exception:
        params = {}
    if "initial_arm_joints" in params:
        return control.compute(
            marker_pos,
            marker_euler,
            hand_j,
            initial_arm_joints=initial_arm_joints,
            reference_arm_joints=reference_arm_joints,
            reference_weights=reference_weights,
        )
    return control.compute(marker_pos, marker_euler, hand_j)


def _np(x):
    return x.detach().cpu().numpy() if torch.is_tensor(x) else np.asarray(x, dtype=np.float64)


def _img_to_uint8_torch(rgb: torch.Tensor) -> torch.Tensor:
    if rgb.dtype == torch.uint8:
        return rgb
    mx = rgb.max().item()
    if mx <= 1.0:
        return torch.clamp(rgb * 255.0, 0.0, 255.0).to(torch.uint8)
    return torch.clamp(rgb, 0.0, 255.0).to(torch.uint8)


def _normalize_blur_kernel(blur_kernel: int) -> int:
    k = max(1, int(blur_kernel))
    if k % 2 == 0:
        k += 1
    return k


def _postprocess_rgb_image(
    image: np.ndarray,
    *,
    brightness_factor: float,
    noise_std: float,
    blur_kernel: int,
) -> np.ndarray:
    img = np.asarray(image, dtype=np.float32)
    img *= float(np.clip(brightness_factor, 0.0, 1.0))
    if noise_std > 0.0:
        img += np.random.normal(0.0, float(noise_std), img.shape).astype(np.float32)
    img = np.clip(img, 0.0, 255.0).astype(np.uint8)
    k = _normalize_blur_kernel(blur_kernel)
    if k > 1:
        try:
            import cv2

            img = cv2.GaussianBlur(img, (k, k), 0)
        except Exception:
            pass
    return img


